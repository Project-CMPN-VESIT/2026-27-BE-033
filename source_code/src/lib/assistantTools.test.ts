test('Every cleaned row reconciles directly to the source workbook', () => {
  const file = path.resolve(source.source);
  assert.deepEqual(build(file), data);
  const w = XLSX.read(fs.readFileSync(file));
  const rows = XLSX.utils.sheet_to_json<unknown[]>(w.Sheets[w.SheetNames[0]], { header: 1 }).slice(1);
  const rupees = (v: unknown) => Number(String(v).replace(/Rs|[\s,]/g, ''));
  assert.equal(data.length, rows.length);
  assert.equal(new Set(data.map(c => c.id)).size, data.length);
  for (const r of rows) {
    const c = data.find(c => c.id === String(r[0]))!;
    assert.equal(c.assets, rupees(r[6])); assert.equal(c.liabilities, rupees(r[7]));
    assert.equal(c.net_worth, rupees(r[6]) - rupees(r[7]));
  }
});
